"""Generate the community replay index from games.csv using Python 3."""

import csv
from collections import defaultdict
from pathlib import Path
from urllib.parse import quote, urlencode


ROOT = Path(__file__).resolve().parents[1]
MATCHUPS = ("TvT", "TvP", "TvZ", "PvP", "PvZ", "ZvZ")
RACES = {"T": "Terran", "P": "Protoss", "Z": "Zerg"}
PAGE_SIZE = 300
GENERATED = "<!-- Generated by tools/build_index.py from games.csv. -->"
RAW_ROOT = "https://raw.githubusercontent.com/simonMoisselin1/pluto-selfplay-replays/main/"
VIEWER = "https://bmnielsen.github.io/openbw-replay-viewer/"


def watch_link(game):
    url = RAW_ROOT + quote(game["replay"], safe="/")
    return "[Watch](" + VIEWER + "?" + urlencode({"rep": url}) + ")"


def page_name(matchup, number):
    return f"{matchup}.md" if number == 1 else f"{matchup}-{number}.md"


def page_link(matchup, number, text):
    return f"[{text}]({page_name(matchup, number)})"


def table_text(value):
    return " ".join(value.splitlines()).replace("&", "&amp;").replace("<", "&lt;").replace(
        ">", "&gt;"
    ).replace("\\", "\\\\").replace("|", "\\|")


def duration(frames):
    seconds = (int(frames) * 42 + 500) // 1000
    return f"{seconds // 60}:{seconds % 60:02d}"


def read_games():
    groups = defaultdict(list)
    digests = set()
    with (ROOT / "games.csv").open(encoding="utf-8", newline="") as stream:
        for line, game in enumerate(csv.DictReader(stream), start=2):
            matchup = game["matchup"]
            group = next((key for key in MATCHUPS if matchup in (key, key[::-1])), None)
            if group is None:
                raise ValueError(f"games.csv line {line} has an unknown matchup: {matchup!r}")
            digest = game["replay_sha256"]
            if digest in digests:
                raise ValueError(f"games.csv line {line} repeats the replay hash {digest}")
            if game["watched"] not in ("yes", "unconfirmed"):
                raise ValueError(f"games.csv line {line} has an unknown watched value")
            if game["playback"] not in ("verified", "unconfirmed"):
                raise ValueError(f"games.csv line {line} has an unknown playback value")
            replay = Path(game["replay"])
            if replay.is_absolute() or ".." in replay.parts or replay.suffix.lower() != ".rep":
                raise ValueError(f"games.csv line {line} has an invalid replay path")
            if not (ROOT / replay).is_file():
                raise FileNotFoundError(f"games.csv line {line}: {replay}")
            digests.add(digest)
            groups[group].append(game)
    for group in groups.values():
        group.sort(key=lambda game: (game["map"].casefold(), int(game["frames"]), game["replay_sha256"]))
    return groups


def counts(games):
    return (
        len(games),
        sum(game["watched"] == "yes" for game in games),
        sum(game["playback"] == "verified" for game in games),
    )


def render_home(groups):
    games = [game for group in groups.values() for game in group]
    total, watched, verified = counts(games)
    lines = [
        "# Pluto vs Pluto · Brood War replays",
        "",
        f"**{total:,} games** · **{watched:,} games marked as watched in full** · "
        f"**{verified:,} replays verified through the final frame by automated playback**",
        "",
        "Both players use a reconstruction of Pluto with its released weights in OpenBW. "
        f"The collection covers {len({game['map_sha256'] for game in games}):,} distinct map files. "
        "Every recording is a complete game. The archive spans several collection runs. "
        "It excludes 352 recordings retired after an earlier version of the bot misread Terran Scanner Sweep effects.",
        "",
        "## Browse by match-up",
        "",
        "| Match-up | Games | Watched in full | Final frame verified | Watch a game |",
        "| --- | ---: | ---: | ---: | --- |",
    ]
    for key in MATCHUPS:
        number, seen, checked = counts(groups[key])
        label = f"{RACES[key[0]]} vs {RACES[key[2]]} ({key})"
        by_length = sorted(groups[key], key=lambda game: int(game["frames"]))
        example = watch_link(by_length[number // 2]) if number else "—"
        lines.append(f"| [{label}](matchups/{page_name(key, 1)}) | {number:,} | {seen:,} | {checked:,} | {example} |")
    lines.extend([
        "",
        "Each page groups both player orders. The race order follows the two players in the replay. "
        "Opening labels show the instructions each player received before the game. `free` means the opening was unrestricted.",
        "",
        "## Watch a game",
        "",
        "Select **Watch** to open a game in the OpenBW browser viewer. On each match-up page, "
        "the replay ID downloads the original `.rep` file. Games are sorted by map and then by duration at Fastest speed.",
        "",
        "The [full index](games.csv) includes the recording source, frame count and SHA-256 of each replay. "
        "A confirmed human viewing means someone has watched the entire game. Automated playback is recorded separately.",
        "",
        "To report a full viewing, open a pull request changing that replay’s `watched` value to `yes` in "
        "`games.csv`, then run `python3 tools/build_index.py` to refresh the counts.",
        "",
        GENERATED,
    ])
    return "\n".join(lines) + "\n"


def render_page(key, games, number, pages):
    first = (number - 1) * PAGE_SIZE
    rows = games[first:first + PAGE_SIZE]
    title = f"{RACES[key[0]]} vs {RACES[key[2]]} ({key})"
    lines = [f"# {title}", "", "[All match-ups](../README.md)", ""]
    if not rows:
        lines.extend(["No replays indexed for this match-up yet.", "", GENERATED])
        return "\n".join(lines) + "\n"
    _, watched, verified = counts(games)
    lines.extend([
        f"**{len(games):,} games** · {watched:,} watched in full · {verified:,} verified by automated playback.",
        "",
    ])
    if pages > 1:
        links = [f"**{index}**" if index == number else page_link(key, index, index) for index in range(1, pages + 1)]
        lines.extend([f"Games {first + 1:,}–{first + len(rows):,} · Pages {' / '.join(links)}", ""])
    lines.extend([
        "| Replay ↓ | Watch | Map | P1 vs P2 | Duration | P1 opening | P2 opening | Watched in full | Final frame verified |",
        "| --- | --- | --- | --- | ---: | --- | --- | --- | --- |",
    ])
    for game in rows:
        path = quote(game["replay"], safe="/")
        link = f"[{game['replay_sha256'][:12]}](../{path}?raw=true)"
        seen = "Yes" if game["watched"] == "yes" else "Unconfirmed"
        checked = "Yes" if game["playback"] == "verified" else "Unconfirmed"
        cells = [
            link, watch_link(game), table_text(game["map"]), game["matchup"], duration(game["frames"]),
            table_text(game["opening_p1"]) or "—", table_text(game["opening_p2"]) or "—", seen, checked,
        ]
        lines.append("| " + " | ".join(cells) + " |")
    if number < pages:
        lines.extend(["", page_link(key, number + 1, "Next page →")])
    lines.extend(["", GENERATED])
    return "\n".join(lines) + "\n"


def main():
    groups = read_games()
    folder = ROOT / "matchups"
    folder.mkdir(exist_ok=True)
    current = set()
    for key in MATCHUPS:
        games = groups[key]
        pages = max(1, (len(games) + PAGE_SIZE - 1) // PAGE_SIZE)
        for number in range(1, pages + 1):
            page = folder / page_name(key, number)
            page.write_text(render_page(key, games, number, pages), encoding="utf-8")
            current.add(page)
    for old_page in folder.glob("*.md"):
        if old_page not in current and old_page.read_text(encoding="utf-8").endswith(GENERATED + "\n"):
            old_page.unlink()
    (ROOT / "README.md").write_text(render_home(groups), encoding="utf-8")


if __name__ == "__main__":
    main()
